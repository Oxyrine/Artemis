"""Lane boundaries. A implements CoreService+PolicyEngine, C implements AuditSink.
B codes only against these; artemis/fakes/ holds fixture-backed stand-ins until the real ones land."""
from __future__ import annotations

from typing import Protocol

from artemis.models import (AgentRun, AllocationResult, CaseState, CoreResult, Evidence, Grade,
                            Hypothesis, ToolCall)


class IllegalTransition(Exception):
    def __init__(self, reason: str):
        super().__init__(reason)
        self.reason = reason


class CoreService(Protocol):  # Lane A. Money in paise; raises models.CoreError on expected failures.
    def new_case_ids(self) -> list[str]: ...
    def opening_context(self, case_id: str) -> dict: ...
    def search_ledger(self, customer_id: str, amount_paise: int | None = None,
                      date_from: str | None = None, date_to: str | None = None,
                      status: str | None = None) -> CoreResult: ...
    def search_bank_receipts(self, customer_id: str | None = None, amount_paise: int | None = None,
                             date_from: str | None = None, date_to: str | None = None,
                             narration_text: str | None = None) -> CoreResult: ...
    def search_remittance_email(self, customer_id: str | None = None, utr: str | None = None,
                                invoice_ids: list[str] | None = None,
                                text: str | None = None) -> CoreResult: ...
    def get_email(self, email_id: str) -> CoreResult: ...
    def get_authorized_tax_credit_extract(self, customer_id: str, quarter: int) -> CoreResult: ...
    def compute_withholding(self, customer_id: str, invoice_ids: list[str],
                            transaction_date: str) -> CoreResult: ...
    def find_credit_notes(self, customer_id: str, invoice_ids: list[str] | None = None) -> CoreResult: ...
    def resolve_customer(self, name_raw: str) -> CoreResult: ...
    def propose_allocation(self, case_id: str, utrs: list[str], allocations: list[dict],
                           adjustments: list[dict]) -> AllocationResult: ...
    def grade(self, case_id: str, allocation: AllocationResult | None,
              evidence: list[Evidence]) -> Grade: ...


class PolicyEngine(Protocol):  # Lane A. The only writer of cases.state.
    def state_of(self, case_id: str) -> CaseState: ...
    def transition(self, case_id: str, to_state: CaseState, actor: str) -> None:
        """Raises IllegalTransition(reason); writes the audit event on success."""


class AuditSink(Protocol):  # Lane C. Payloads carry references and hashes, never raw bodies.
    def append(self, case_id: str | None, event_type: str, actor: str, payload: dict) -> None: ...


class RunStore(Protocol):  # B's tables: agent_runs, tool_calls, hypotheses, evidence, batches.
    def next_id(self, prefix: str) -> str: ...
    def save_run(self, run: AgentRun) -> None: ...
    def get_run(self, run_id: str) -> AgentRun: ...
    def runs(self, case_id: str | None = None) -> list[AgentRun]: ...
    def add_tool_call(self, call: ToolCall) -> None: ...
    def tool_calls(self, run_id: str) -> list[ToolCall]: ...
    def add_hypothesis(self, h: Hypothesis) -> None: ...
    def hypotheses(self, run_id: str) -> list[Hypothesis]: ...
    def add_evidence(self, ev: Evidence) -> None: ...
    def evidence(self, case_id: str) -> list[Evidence]: ...
    def save_outcome(self, outcome: "CaseOutcome") -> None: ...  # noqa: F821
    def get_outcome(self, case_id: str) -> "CaseOutcome": ...  # noqa: F821
    def outcomes(self) -> list["CaseOutcome"]: ...  # noqa: F821
    def save_batch(self, batch: "BatchStatus") -> None: ...  # noqa: F821
    def get_batch(self, batch_id: str) -> "BatchStatus": ...  # noqa: F821
